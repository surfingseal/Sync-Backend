type MoodAudit struct {
	SearchRank                 int      `json:"search_rank"`
	SearchRankContribution     float64  `json:"search_rank_contribution"`
	MoodKeywordContribution    float64  `json:"mood_keyword_contribution"`
	GenreKeywordContribution   float64  `json:"genre_keyword_contribution"`
	PreferredGenreContribution float64  `json:"preferred_genre_contribution"`
	LanguageContribution       float64  `json:"language_contribution"`
	MoodKeywordMatches         []string `json:"mood_keyword_matches"`
	GenreKeywordMatches        []string `json:"genre_keyword_matches"`
	TitleMoodMatches           []string `json:"title_mood_matches"`
	Score                      float64  `json:"mood_score"`
	TempoCompatibility         string   `json:"tempo_compatibility"`
	EnergyCompatibility        string   `json:"energy_compatibility"`
}

func AuditMood(v model.YouTubeVideo, rank int, a model.ImageAnalysis, p model.MusicPreferences) MoodAudit {
	text := v.Title + " " + v.Description + " " + v.ChannelTitle
	genreWeight := .30
	if len(p.PreferredGenres) == 0 {
		genreWeight = .40
	}
	r := MoodAudit{SearchRank: rank, SearchRankContribution: .15 * clamp(1-float64(rank)/20), MoodKeywordContribution: .40 * matchFraction(text, a.Mood.Tags), GenreKeywordContribution: genreWeight * matchFraction(text, a.MusicProfile.Genres), PreferredGenreContribution: .10 * matchFraction(text, p.PreferredGenres), Score: moodScore(v, rank, a, p), TempoCompatibility: "not used by current formula; no audio tempo evidence", EnergyCompatibility: "not used by current formula; no audio energy evidence", MoodKeywordMatches: []string{}, GenreKeywordMatches: []string{}, TitleMoodMatches: []string{}}
	if languageMatch(v, p) {
		r.LanguageContribution = .05
	}
	for _, tag := range a.Mood.Tags {
		if phrase(text, tag) {
			r.MoodKeywordMatches = append(r.MoodKeywordMatches, tag)
		}
		if phrase(v.Title, tag) {
			r.TitleMoodMatches = append(r.TitleMoodMatches, tag)
		}
	}
	for _, g := range a.MusicProfile.Genres {
		if phrase(text, g) {
			r.GenreKeywordMatches = append(r.GenreKeywordMatches, g)
		}
	}
	return r
}
